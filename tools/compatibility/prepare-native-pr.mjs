import { readFileSync, appendFileSync } from 'node:fs';
import { github, repository } from './lib/github.mjs';
import { maintainerReview } from './lib/pr-evidence.mjs';
import { revisionId } from '../docs/lib/revisions.mjs';
const event = JSON.parse(readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'));
const repo = repository(process.env.GITHUB_REPOSITORY);
if (repo !== 'sbox-cool/sbox-network-storage') throw new Error('Unexpected native source repository');
const { pr, head, server_ref: serverRef } = event.inputs ?? {};
if (!/^[1-9]\d*$/.test(pr ?? '') || !/^[a-f0-9]{40}$/.test(head ?? '') || !/^v\d+\.\d+\.\d+$/.test(serverRef ?? '')) throw new Error('Select an exact PR number/head and stable server tag');
if (process.env.SBOX_CERTIFICATION_RUNNER_ENABLED !== 'true' || !process.env.SBOX_GAME) throw new Error('Configure an approved sbox-native runner, SBOX_GAME and SBOX_CERTIFICATION_RUNNER_ENABLED=true. No native evidence is certified.');
const token = process.env.GITHUB_TOKEN;
const pull = await github(`/repos/${repo}/pulls/${pr}`, { token });
if (pull.state !== 'open' || pull.head.sha !== head || pull.head.repo.full_name !== repo) throw new Error('Native execution is limited to the reviewed exact head of an open same-repository PR; fork code is never run on a persistent runner.');
const review = await maintainerReview(repo, pr, head, token);
if (!review) throw new Error('A maintainer exact-head /compatibility-review acknowledgement is required before executing candidate code.');
const response = await fetch('https://public.facepunch.com/sbox/package/get/2/sboxcool.network-storage', { signal: AbortSignal.timeout(30_000) });
if (!response.ok) throw new Error(`Published baseline metadata returned HTTP ${response.status}`);
const baseline = revisionId((await response.json()).Version?.Id);
appendFileSync(process.env.GITHUB_OUTPUT, `head=${head}\npr=${pr}\nserver_ref=${serverRef}\nbaseline=${baseline}\n`);
